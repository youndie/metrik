package ru.workinprogress.metrik.agent

/**
 * Превращает имя хоста в числовой адрес.
 *
 * На JVM это лишний шаг — `InetSocketAddress` резолвит имя сам. На Kotlin/Native не резолвит
 * никто: имя доезжает до сокета как есть, и `connect` падает с EINVAL. Агент ошибки отправки
 * глотает по контракту, поэтому наружу это выглядело как «агент молчит», а не как «агент не умеет
 * доменные имена» — и прожило до прода, где endpoint всегда доменный.
 *
 * Разрешение делается на каждое подключение, а не один раз: адрес пода meтrik меняется при
 * переезде, и закешированный адрес пережил бы его молча.
 */
internal expect fun resolveHost(host: String): String
