package ru.workinprogress.metrik.server

/**
 * Настройка сборщика Kotlin/Native из переменных окружения.
 *
 * По умолчанию не делает ничего: рычаги включаются явно, чтобы их можно было мерить на стенде,
 * не пересобирая образ. Прошлая попытка задать жёсткий `maxHeapBytes` в половину лимита
 * контейнера сделала хуже — при спросе выше потолка рантайм уходит в непрерывные сборки
 * (об этом прямо предупреждает документация GC), и под умирал быстрее, чем без настройки.
 */
expect fun tuneGc(
    targetHeapBytes: Long?,
    targetUtilization: Double?,
): String?
